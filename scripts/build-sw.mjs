// Writes dist/sw.js after `vite build` (spec stories 8, 9: a second visit opens at once and works offline).
// Every served file is precached under its content hash. A new deploy copies unchanged files from the previous
// cache instead of downloading the 20+ MB Python runtime and Skill package again. Pages are network-first so a
// new deploy is picked up when online; everything else is served from the cache.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const DIST = join(dirname(fileURLToPath(import.meta.url)), '..', 'dist');
// Served but never needed offline: host config, release paperwork, and the social preview image.
const SKIP = new Set(['sw.js', '_headers', 'skill/SHA256SUMS', 'skill/CI-PROVENANCE.json', 'art/og.jpg']);

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const files = Object.fromEntries(walk(DIST)
  .map((path) => relative(DIST, path).replaceAll('\\', '/'))
  .filter((path) => !SKIP.has(path))
  .sort()
  .map((path) => [`/${path}`, createHash('sha256').update(readFileSync(join(DIST, path))).digest('hex').slice(0, 16)]));
const version = createHash('sha256').update(JSON.stringify(files)).digest('hex').slice(0, 12);

const worker = `// Generated by scripts/build-sw.mjs; do not edit.
const VERSION = ${JSON.stringify(version)};
const FILES = ${JSON.stringify(files)};
const CACHE = 'temple-' + VERSION;
const scope = new URL(self.registration.scope);
const key = (path, rev) => new URL('.' + path + '?__rev=' + rev, scope).href;
const pathOf = (url) => '/' + url.pathname.slice(scope.pathname.length);

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    const older = (await caches.keys()).filter((name) => name.startsWith('temple-') && name !== CACHE);
    for (const [path, rev] of Object.entries(FILES)) {
      const id = key(path, rev);
      if (await cache.match(id)) continue;
      let response = null;
      for (const name of older) {
        response = await (await caches.open(name)).match(id);
        if (response) break;
      }
      response ??= await fetch(new URL('.' + path, scope), { cache: 'no-cache' });
      if (!response.ok) throw new Error(path + ' answered ' + response.status);
      await cache.put(id, response);
    }
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    for (const name of await caches.keys()) {
      if (name.startsWith('temple-') && name !== CACHE) await caches.delete(name);
    }
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== scope.origin || !url.pathname.startsWith(scope.pathname)) return;
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).catch(() => caches.match(key('/index.html', FILES['/index.html']))));
    return;
  }
  const rev = FILES[pathOf(url)];
  if (!rev) return;
  event.respondWith(caches.match(key(pathOf(url), rev)).then((hit) => hit ?? fetch(request)));
});
`;
writeFileSync(join(DIST, 'sw.js'), worker);
const bytes = Object.keys(files).reduce((sum, path) => sum + statSync(join(DIST, path.slice(1))).size, 0);
console.log(`build-sw: ${Object.keys(files).length} files, ${(bytes / 1e6).toFixed(1)} MB, version ${version}`);
